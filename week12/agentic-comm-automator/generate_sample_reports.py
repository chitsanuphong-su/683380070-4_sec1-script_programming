import os
import datetime
from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas
import openpyxl

def generate_samples(base_dir):
    os.makedirs(base_dir, exist_ok=True)
    today_str = datetime.date.today().strftime("%Y-%m-%d")

    # 1. Generate sales_report.pdf
    pdf_path = os.path.join(base_dir, "sales_report.pdf")
    c = canvas.Canvas(pdf_path, pagesize=letter)
    c.setFont("Helvetica-Bold", 18)
    c.drawString(100, 750, "DAILY SALES REPORT")
    c.setFont("Helvetica", 12)
    c.drawString(100, 710, "Report Name: DailySalesSummary")
    c.drawString(100, 690, f"Report Date: {today_str}")
    c.drawString(100, 670, "Total Sales: $12,345.67")
    c.drawString(100, 650, "Total Customers: 500")
    c.drawString(100, 610, "Generated by: Week 12 Agentic Communication Automator")
    c.save()
    print(f"Created PDF: {pdf_path}")

    # 2. Generate summary_data.xlsx
    xlsx_path = os.path.join(base_dir, "summary_data.xlsx")
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Sales Summary"
    ws.append(["Metric", "Value"])
    ws.append(["Report Name", "DailySalesSummary"])
    ws.append(["Report Date", today_str])
    ws.append(["Total Sales", 12345.67])
    ws.append(["Total Customers", 500])
    wb.save(xlsx_path)
    print(f"Created XLSX: {xlsx_path}")

if __name__ == "__main__":
    target_dir = os.path.join(os.path.dirname(__file__), "data", "reports")
    generate_samples(target_dir)
