# agentic-document-automator/main.py
import sys
import os

# Add the project directory and 'src' directory to Python path
base_dir = os.path.dirname(os.path.abspath(__file__))
src_dir = os.path.join(base_dir, 'src')
if src_dir not in sys.path:
    sys.path.insert(0, src_dir)
if base_dir not in sys.path:
    sys.path.insert(0, base_dir)

from config_parser import ConfigParser
from document_agent import DocumentAgent
from utils import setup_logging, ensure_directory_exists

logger = setup_logging(__name__)


def check_required_files(config, base_dir):
    """
    Checks if all input files specified in each task definition exist.
    Inspects dynamically by task type rather than assuming fixed indexes.
    """
    required_files_exist = True
    for i, task in enumerate(config.get('tasks', [])):
        task_type = task.get('type')
        task_name = task.get('name', f"Task {i}")

        if task_type == 'generate_word_report':
            template_path = task.get('template_path')
            if not template_path or not os.path.exists(template_path):
                logger.critical(f"[{task_name}] Required Word template '{template_path}' not found.")
                required_files_exist = False

        elif task_type == 'apply_pdf_watermark':
            input_pdf = task.get('input_pdf')
            if not input_pdf or not os.path.exists(input_pdf):
                logger.critical(f"[{task_name}] Required source PDF '{input_pdf}' not found.")
                required_files_exist = False

        elif task_type == 'merge_pdfs':
            input_pdfs = task.get('input_pdfs', [])
            for pdf_path in input_pdfs:
                if not pdf_path or not os.path.exists(pdf_path):
                    logger.critical(f"[{task_name}] Required dummy PDF for merging '{pdf_path}' not found.")
                    required_files_exist = False

        elif task_type == 'extract_word_text':
            input_docx = task.get('input_docx')
            # If the input docx is generated by an earlier task in the sequence, check if predecessor produces it
            # Otherwise check directly on disk
            if input_docx and not os.path.exists(input_docx):
                # Check if an earlier task generates this file
                is_generated_earlier = any(
                    t.get('output_path') == input_docx for t in config.get('tasks', [])[:i]
                )
                if not is_generated_earlier:
                    logger.critical(f"[{task_name}] Required Word input '{input_docx}' not found.")
                    required_files_exist = False

        elif task_type == 'extract_pdf_text':
            input_pdf = task.get('input_pdf')
            if input_pdf and not os.path.exists(input_pdf):
                is_generated_earlier = any(
                    t.get('output_pdf') == input_pdf for t in config.get('tasks', [])[:i]
                )
                if not is_generated_earlier:
                    logger.critical(f"[{task_name}] Required PDF input '{input_pdf}' not found.")
                    required_files_exist = False

    return required_files_exist


def main():
    """
    Main entry point for the Agentic Document Processor.
    Loads config and runs the agent.
    """
    current_dir = os.path.dirname(os.path.abspath(__file__))
    config_file_path = os.path.join(current_dir, 'configs', 'document_automation_config.json')

    try:
        # Ensure output directories exist
        ensure_directory_exists(os.path.join(current_dir, 'documents'))
        ensure_directory_exists(os.path.join(current_dir, 'templates'))
        ensure_directory_exists(os.path.join(current_dir, 'documents', 'reports'))

        logger.info(f"Loading configuration from: {config_file_path}")
        config_parser = ConfigParser(config_file_path)
        config = config_parser.load_config()

        # Update paths in config to be absolute based on project root (current_dir)
        for key, value in config.get('output_files', {}).items():
            if not os.path.isabs(value):
                config['output_files'][key] = os.path.normpath(os.path.join(current_dir, value))

        for task in config.get('tasks', []):
            if 'template_path' in task and not os.path.isabs(task['template_path']):
                task['template_path'] = os.path.normpath(os.path.join(current_dir, task['template_path']))
            if 'input_pdf' in task and not os.path.isabs(task['input_pdf']):
                task['input_pdf'] = os.path.normpath(os.path.join(current_dir, task['input_pdf']))
            if 'output_pdf' in task and not os.path.isabs(task['output_pdf']):
                task['output_pdf'] = os.path.normpath(os.path.join(current_dir, task['output_pdf']))
            if 'input_pdfs' in task:
                task['input_pdfs'] = [
                    os.path.normpath(os.path.join(current_dir, p)) if not os.path.isabs(p) else p
                    for p in task['input_pdfs']
                ]
            if 'input_docx' in task and not os.path.isabs(task['input_docx']):
                task['input_docx'] = os.path.normpath(os.path.join(current_dir, task['input_docx']))
            if 'output_text_file' in task and not os.path.isabs(task['output_text_file']):
                task['output_text_file'] = os.path.normpath(os.path.join(current_dir, task['output_text_file']))
            if 'output_path' in task and not os.path.isabs(task['output_path']):
                task['output_path'] = os.path.normpath(os.path.join(current_dir, task['output_path']))

        # Check if all required initial input files exist
        if not check_required_files(config, current_dir):
            logger.critical("One or more required input files are missing. Please create them as per README.md and config.")
            sys.exit(1)

        logger.info("Initializing Document Agent...")
        agent = DocumentAgent(config)

        logger.info("Running Document Agent workflow...")
        success = agent.run()

        if success:
            logger.info("Document automation process completed successfully.")
            return 0
        else:
            logger.error("Document automation completed with one or more task errors.")
            return 1

    except FileNotFoundError as e:
        logger.critical(f"File system error: {e}")
        logger.info("Please ensure all specified input files and configurations exist.")
        sys.exit(1)
    except ValueError as e:
        logger.critical(f"Configuration error: {e}")
        logger.info("Please check the format and required fields in your config file.")
        sys.exit(1)
    except ImportError as e:
        logger.critical(f"Missing required library: {e}. Please ensure all dependencies are installed (pip install -r requirements.txt).")
        sys.exit(1)
    except Exception as e:
        logger.critical(f"An unexpected critical error occurred during execution: {e}", exc_info=True)
        sys.exit(1)


if __name__ == "__main__":
    exit_code = main()
    sys.exit(exit_code if exit_code is not None else 0)
